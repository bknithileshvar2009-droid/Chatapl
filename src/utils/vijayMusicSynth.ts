// Cache generated WAV audio Data URLs for instant playback across HTML5 <audio> elements
const wavDataUrlCache: Record<string, string> = {};

/**
 * Synthesizes a high-energy 10-second looping Vijay beat WAV file entirely in-memory using Web Audio API!
 * Guarantees 100% offline, cross-platform audio playback with ZERO 404 or CORS errors.
 */
export function generateVijaySongAudioWav(trackId: string): string {
  if (wavDataUrlCache[trackId]) {
    return wavDataUrlCache[trackId];
  }

  const sampleRate = 22050; // Lower sample rate for lightweight instant generation
  const duration = 8; // 8 seconds loop
  const totalSamples = sampleRate * duration;

  const track = VIJAY_MUSIC_CATALOG.find((t) => t.id === trackId) || VIJAY_MUSIC_CATALOG[0];
  const bpm = track.bpm || 128;
  const beatInterval = 60 / bpm; // seconds per beat

  const buffer = new Float32Array(totalSamples);

  // Notes frequencies for Vijay energetic melodies (Pentatonic / Mass roots)
  const notes = [220, 247.5, 275, 330, 371.25, 440, 495, 550, 660];

  for (let i = 0; i < totalSamples; i++) {
    const time = i / sampleRate;
    const currentBeat = (time / beatInterval) % 16;
    const beatIndex = Math.floor(currentBeat);

    // 1. Heavy Bass Kick Drum on every quarter beat
    let sample = 0;
    const beatTime = (time % beatInterval);
    if (beatTime < 0.15) {
      const kickFreq = 120 * Math.exp(-beatTime * 30);
      sample += Math.sin(2 * Math.PI * kickFreq * beatTime) * Math.exp(-beatTime * 15) * 0.6;
    }

    // 2. Snare / Clap on beats 2, 4, 6, 8, 10, 12, 14, 16
    if (beatIndex % 2 === 1 && beatTime < 0.1) {
      const noise = (Math.random() * 2 - 1) * Math.exp(-beatTime * 25);
      sample += noise * 0.35;
    }

    // 3. Fast Synth Lead Arpeggio (Iconic Tamil Vijay Melody Hook)
    const noteIdx = (beatIndex * 3 + Math.floor(beatTime * 8)) % notes.length;
    const leadFreq = notes[noteIdx];
    const leadEnv = Math.exp(-(beatTime % 0.125) * 12);
    const synthTone = Math.sin(2 * Math.PI * leadFreq * time) + 0.5 * Math.sin(4 * Math.PI * leadFreq * time);
    sample += synthTone * leadEnv * 0.25;

    // 4. Sub Bassline Pulse
    const bassFreq = notes[beatIndex % 4] / 2;
    sample += Math.sin(2 * Math.PI * bassFreq * time) * 0.2;

    buffer[i] = Math.max(-1, Math.min(1, sample));
  }

  // Encode Float32Array to WAV PCM Data URL
  const wavBytes = encodeWAV(buffer, sampleRate);
  let binary = '';
  const bytes = new Uint8Array(wavBytes);
  const len = bytes.byteLength;
  for (let i = 0; i < len; i++) {
    binary += String.fromCharCode(bytes[i]);
  }
  const base64 = btoa(binary);
  const dataUrl = `data:audio/wav;base64,${base64}`;
  wavDataUrlCache[trackId] = dataUrl;
  return dataUrl;
}

function encodeWAV(samples: Float32Array, sampleRate: number): ArrayBuffer {
  const buffer = new ArrayBuffer(44 + samples.length * 2);
  const view = new DataView(buffer);

  /* RIFF identifier */
  writeString(view, 0, 'RIFF');
  /* RIFF chunk length */
  view.setUint32(4, 36 + samples.length * 2, true);
  /* RIFF type */
  writeString(view, 8, 'WAVE');
  /* format chunk identifier */
  writeString(view, 12, 'fmt ');
  /* format chunk length */
  view.setUint32(16, 16, true);
  /* sample format (raw) */
  view.setUint16(20, 1, true);
  /* channel count (1 = mono) */
  view.setUint16(22, 1, true);
  /* sample rate */
  view.setUint32(24, sampleRate, true);
  /* byte rate (sample rate * block align) */
  view.setUint32(28, sampleRate * 2, true);
  /* block align (channel count * bytes per sample) */
  view.setUint16(32, 2, true);
  /* bits per sample */
  view.setUint16(34, 16, true);
  /* data chunk identifier */
  writeString(view, 36, 'data');
  /* data chunk length */
  view.setUint32(40, samples.length * 2, true);

  /* float to 16-bit PCM */
  let offset = 44;
  for (let i = 0; i < samples.length; i++, offset += 2) {
    const s = Math.max(-1, Math.min(1, samples[i]));
    view.setInt16(offset, s < 0 ? s * 0x8000 : s * 0x7fff, true);
  }

  return buffer;
}

function writeString(view: DataView, offset: number, string: string) {
  for (let i = 0; i < string.length; i++) {
    view.setUint8(offset + i, string.charCodeAt(i));
  }
}

